Pt = Tuple[float, float]
StrokeT = List[Pt]


def arc(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float, n: int = 24) -> StrokeT:
    """橢圓弧；角度以度為單位，y 向下（270° 在正上方，90° 在正下方）。"""
    pts = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


def line(*pts: Pt) -> StrokeT:
    return list(pts)


